package com.rafaeloliveira.bilheteria.feature.ticketing.domain.model

import java.time.Instant

/** Identifier generated by the app and sent to Cielo as `reference` (BR-08). UUID v4. */
@JvmInline
value class PurchaseReference(
    val value: String,
) {
    init {
        require(value.isNotBlank()) { "Reference cannot be blank" }
    }
}

/** Lifecycle of a purchase (spec, status table). Only Pending and Recovering are "open" (BR-10). */
enum class PurchaseStatus {
    Pending,
    Recovering,
    Approved,
    Declined,
    Cancelled,
    Failed,
    ;

    val isOpen: Boolean get() = this == Pending || this == Recovering

    /** Results shown in the history (BR-18): sales, not technical failures. */
    val isSale: Boolean get() = this == Approved || this == Declined || this == Cancelled
}

/** Why a purchase ended as [PurchaseStatus.Failed] (BR-14, BR-15). */
enum class FailureReason { TerminalAppUnavailable, Generic, Authentication, NotFound }

/** Transaction data kept for the receipt (BR-16). No card data: Cielo never sends the PAN to the app. */
data class TransactionData(
    val orderId: String,
    val authCode: String,
    val nsu: String,
    val brand: String?,
)

/** A purchase as recorded locally. Event fields are a snapshot, so the receipt survives catalog changes. */
data class Purchase(
    val id: String,
    val reference: PurchaseReference,
    val eventId: String,
    val eventName: String,
    val eventStartsAt: Instant,
    val venue: String,
    val unitPrice: Money,
    val quantity: Int,
    val total: Money,
    val status: PurchaseStatus,
    val failureReason: FailureReason?,
    val transaction: TransactionData?,
    val createdAt: Instant,
    val updatedAt: Instant,
)
