import com.rafaeloliveira.bilheteria.buildlogic.configureUnitTests
import com.rafaeloliveira.bilheteria.buildlogic.libs
import com.rafaeloliveira.bilheteria.buildlogic.version
import org.gradle.api.Plugin
import org.gradle.api.Project
import org.gradle.kotlin.dsl.configure

/** :app (id: app.android.application). SDKs, build types, R8, versioning and module graph rules (S-12). */
class AndroidApplicationConventionPlugin : Plugin<Project> {
    override fun apply(target: Project) {
        with(target) {
            pluginManager.apply("com.android.application")
            pluginManager.apply("app.quality")
            pluginManager.apply("com.jraska.module.graph.assertion")

            // versionCode is generated by CI (GITHUB_RUN_NUMBER); never edited by hand.
            val runNumber = providers.environmentVariable("GITHUB_RUN_NUMBER").orNull?.toIntOrNull() ?: 1

            extensions.configure<ApplicationExtension> {
                compileSdk = libs.version("compileSdk").toInt()
                defaultConfig {
                    minSdk = libs.version("minSdk").toInt()
                    targetSdk = libs.version("targetSdk").toInt()
                    versionCode = runNumber
                    versionName = "0.2.0"
                }
                buildTypes {
                    getByName("debug") {
                        applicationIdSuffix = ".debug"
                    }
                    getByName("release") {
                        isMinifyEnabled = true
                        isShrinkResources = true
                        isDebuggable = false
                        proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
                    }
                }
                compileOptions.configureJava()
                lint.configureLint(target)
            }
            addDesugaring()
            configureKotlin()
            configureUnitTests()
            configureModuleGraph()
        }
    }

    private fun Project.configureModuleGraph() {
        val features =
            rootDir
                .resolve("feature")
                .listFiles()
                ?.filter { it.isDirectory }
                ?.map { it.name }
                .orEmpty()
        extensions.configure<GraphRulesExtension> {
            maxHeight = MAX_HEIGHT
            restricted = arrayOf(
                ":core:.* -X> :feature:.*",
                ".*:domain -X> .*:(data|ui)",
                ".*:ui -X> .*:data",
                ".*:api -X> .*:(domain|data|ui)",
            ) + features.map { name -> ":feature:$name:.* -X> :feature:(?!$name:)[^:]+:(domain|data|ui)" }
        }
    }

    private companion object {
        const val MAX_HEIGHT = 6
    }
}
